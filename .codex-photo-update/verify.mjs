import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const artifactDir = path.dirname(fileURLToPath(import.meta.url));
const projectDir = path.resolve(artifactDir, '..');
const mode = process.argv[2];
if (!['baseline', 'modified'].includes(mode)) throw new Error('Usage: node verify.mjs baseline|modified [html-path]');
const defaultFile = mode === 'baseline' ? path.join(artifactDir, 'original.html') : path.join(artifactDir, 'MODIFIED_FILE.html');
const file = path.resolve(process.argv[3] || defaultFile);
const html = fs.readFileSync(file, 'utf8');
const original = fs.readFileSync(path.join(artifactDir, 'original.html'), 'utf8');
const fail = message => { console.error(`FAIL ${message}`); process.exit(1); };
const block = (source, start, end) => {
  const from = source.indexOf(start);
  if (from < 0) return null;
  const to = source.indexOf(end, from + start.length);
  return to < 0 ? null : source.slice(from, to + end.length);
};
const equal = (a, b) => a !== null && b !== null && a === b;
const headerOriginal = block(original, '<header id="hd">', '</header>');
const heroCssOriginal = block(original, '/* hero */', '/* areas */');
const heroMarkupOriginal = block(original, '<section id="inicio" class="hero">', '</section>');
const headerCurrent = block(html, '<header id="hd">', '</header>');
const heroCssCurrent = block(html, '/* hero */', '/* areas */');
const heroMarkupCurrent = block(html, '<section id="inicio" class="hero">', '</section>');
const heroVars = source => [...source.matchAll(/--hero:url\("data:image\/webp;base64,[^"]+"\)/g)].map(match => match[0]);
const baseHeroVars = heroVars(original);
const currentHeroVars = heroVars(html);
const scripts = [...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
try {
  if (!scripts.length) throw new Error('No inline scripts found');
  scripts.forEach((script, index) => new vm.Script(script[1], { filename: `inline-script-${index + 1}.js` }));
} catch (error) { fail(`inline_js_syntax ${error.message}`); }
if (!equal(headerOriginal, headerCurrent)) fail('header changed');
if (!equal(heroCssOriginal, heroCssCurrent)) fail('hero CSS changed');
if (!equal(heroMarkupOriginal, heroMarkupCurrent)) fail('hero markup changed');
if (JSON.stringify(baseHeroVars) !== JSON.stringify(currentHeroVars)) fail('--hero value changed');

if (mode === 'baseline') {
  const oldRecRefs = (html.match(/var\(--rec\)/g) || []).length;
  if (html.includes('<section id="escritorio"') || oldRecRefs !== 2 || html.includes('id="office-lightbox"')) fail('unexpected baseline state');
  console.log('mode=baseline');
  console.log(`file=${file}`);
  console.log('header=PASS');
  console.log('hero_css=PASS');
  console.log('hero_markup=PASS');
  console.log(`hero_values=${baseHeroVars.length};unchanged=PASS`);
  console.log('inline_js_syntax=PASS');
  console.log('gallery=ABSENT');
  console.log(`rec_refs=${oldRecRefs}`);
  console.log('baseline_state=PASS');
  process.exit(0);
}

const galleryStart = html.indexOf('<section id="escritorio"');
const depoStart = html.indexOf('<section id="depoimentos"');
const aboutEnd = html.indexOf('</section>', html.indexOf('<section id="sobre"'));
const gallery = galleryStart >= 0 && depoStart > galleryStart ? html.slice(galleryStart, depoStart) : '';
const galleryFigures = [...gallery.matchAll(/<figure class="office-card office-(?:main|logo|detail)\b/g)];
const galleryImages = [...gallery.matchAll(/<img\b[^>]*>/g)].map(match => match[0]);
const galleryLinks = [...gallery.matchAll(/<a class="office-image office-link"[^>]*>/g)];
const expectedCaptions = ['Sala de atendimento', 'Marca do escritório', 'Detalhe da Justiça', 'Biblioteca jurídica', 'Estante e detalhes'];
const captionsPass = expectedCaptions.every(caption => gallery.includes(`data-caption="${caption}"`));
const imageAttrsPass = galleryImages.length === 5 && galleryImages.every(img => /srcset="[^"]+"/.test(img) && /sizes="[^"]+"/.test(img) && /width="\d+"/.test(img) && /height="\d+"/.test(img) && /loading="lazy"/.test(img) && /decoding="async"/.test(img) && /alt="[^"]+"/.test(img));
if (!aboutEnd || !(aboutEnd < galleryStart && galleryStart < depoStart)) fail('gallery order');
if (galleryFigures.length !== 5 || galleryLinks.length !== 5 || !captionsPass) fail(`gallery figures=${galleryFigures.length}, links=${galleryLinks.length}, captions=${captionsPass}`);
if (!imageAttrsPass) fail('gallery responsive image attributes');
if (!html.includes('<dialog class="office-dialog" id="office-lightbox"') || !html.includes('officeDialog.showModal()') || !html.includes("officeDialog.addEventListener('close'") || !html.includes("e.key==='ArrowLeft'") || !html.includes("e.key==='ArrowRight'") || !html.includes("officePrev.addEventListener('click'") || !html.includes("officeNext.addEventListener('click'") || !html.includes('officeReturn?.focus({preventScroll:true})')) fail('native gallery dialog controls');
if (!html.includes('.office-dialog__image{') || !html.includes('object-fit:contain')) fail('modal image fit');
const aboutPicture=html.includes('<picture class="ph abi"><source media="(max-width:700px)"')&&html.includes('sala-480.webp 480w, assets/escritorio/sala-960.webp 960w, assets/escritorio/sala-1440.webp 1440w');
const contactDesktop=html.includes('<picture class="ph cph"><source media="(min-width:1361px)" srcset="assets/escritorio/marca-480.webp 480w, assets/escritorio/marca-960.webp 960w, assets/escritorio/marca-1086.webp 1086w"');
const contactFallback=html.includes('src="assets/escritorio/sala-960.webp" srcset="assets/escritorio/sala-480.webp 480w, assets/escritorio/sala-960.webp 960w, assets/escritorio/sala-1440.webp 1440w"');
const contactFit=html.includes('.cph .office-photo{position:absolute;inset:0;width:100%;height:100%;object-fit:cover;background:#e9e3d9}');
const aboutDesktopFit=html.includes('.abi .office-photo{object-fit:cover;object-position:center 42%}');
const aboutMobileFrame=html.includes('.abi{height:240px;min-height:220px}')&&html.includes('.abi:before{background:linear-gradient(180deg,rgba(11,33,70,.24),transparent 15%)}');
const modalMobileFit=html.includes('@media(max-width:600px){.office-dialog__stage{position:relative;display:block;width:100%;max-width:none;padding-bottom:48px}')&&html.includes('#office-lightbox-prev,#office-lightbox-next{position:absolute;bottom:0;left:0;width:44px;height:44px}');
if(!aboutPicture||!contactDesktop||!contactFallback||!contactFit||!aboutDesktopFit||!aboutMobileFrame||html.includes('var(--rec)')||/--rec\s*:/.test(html))fail('responsive About/Contact photo slots');
if(!modalMobileFit)fail('mobile modal controls and image stage');
const assetRefs = [...new Set([...html.matchAll(/assets\/escritorio\/[A-Za-z0-9-]+\.webp/g)].map(match => match[0]))];
const missing = assetRefs.filter(relative => !fs.existsSync(path.join(projectDir, relative)));
const expected = ['sala-480.webp','sala-960.webp','sala-1440.webp','marca-480.webp','marca-960.webp','marca-1086.webp','contato-480.webp','contato-960.webp','contato-1440.webp','justica-480.webp','justica-960.webp','justica-1086.webp','biblioteca-480.webp','biblioteca-960.webp','biblioteca-1086.webp','estante-480.webp','estante-960.webp','estante-1440.webp'];
const badWebp = expected.filter(name => {
  const full = path.join(projectDir, 'assets', 'escritorio', name);
  if (!fs.existsSync(full)) return true;
  const bytes = fs.readFileSync(full);
  return bytes.length < 16 || bytes.subarray(8, 12).toString('ascii') !== 'WEBP';
});
const referencedExpected=expected.filter(name=>!name.startsWith('contato-'));
if (missing.length || badWebp.length || assetRefs.length !== referencedExpected.length) fail(`assets refs=${assetRefs.length}, missing=${missing.join(',')}, invalid=${badWebp.join(',')}`);
const assetBytes = expected.reduce((total, name) => total + fs.statSync(path.join(projectDir, 'assets', 'escritorio', name)).size, 0);
const recRemoved = !html.includes('var(--rec)') && !/--rec\s*:/.test(html);
const oldModalPreserved = block(original, '<div id="lb"', '</div>') === block(html, '<div id="lb"', '</div>');
const noNewDataUris = (html.match(/data:image\/[^;]+;base64,/g) || []).length === (original.match(/data:image\/[^;]+;base64,/g) || []).length - 1;
if (!oldModalPreserved || !recRemoved || !noNewDataUris) fail('existing lightbox or embedded image payload changed unexpectedly');
console.log('mode=modified');
console.log(`file=${file}`);
console.log('header=PASS');
console.log('hero_css=PASS');
console.log('hero_markup=PASS');
console.log(`hero_values=${currentHeroVars.length};unchanged=PASS`);
console.log('inline_js_syntax=PASS');
console.log('gallery_items=5');
console.log('gallery_order=PASS');
console.log('gallery_responsive_images=PASS');
console.log('native_dialog_keyboard_focus_scroll=PASS');
console.log('about_contact_responsive=PASS');
console.log('contact_desktop_portrait=PASS');
console.log('contact_fallback_landscape=PASS');
console.log('about_mobile_fullbleed=PASS');
console.log('mobile_modal_full_width=PASS');
console.log(`asset_refs=${assetRefs.length};webp_variants=${expected.length};bytes=${assetBytes}`);
console.log('existing_lightbox=PASS');
console.log('old_rec_removed=PASS');
console.log('no_new_base64=PASS');